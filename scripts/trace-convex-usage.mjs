#!/usr/bin/env node
/**
 * Legacy Convex function-reference inventory for the Turso API cutover.
 *
 * WHY THIS EXISTS. The cutover gates (`docs/convex-to-neon-cutover-gates.md`)
 * require a recorded, function-level list of what the frontend still asks
 * Convex for, checked against the endpoints `api/src/server.ts` actually
 * serves. The route audit doc has that at screen granularity; this script
 * produces it at call-site granularity so a migrated screen can be proved
 * migrated instead of assumed.
 *
 * It is read-only and dependency-free. Run:
 *   node scripts/trace-convex-usage.mjs            # refresh docs/neon-migration-trace.md
 *   node scripts/trace-convex-usage.mjs --check    # compare the committed inventory
 *
 * Output is factual: which Convex functions the frontend references, and which
 * HTTP routes exist. Module -> route coverage below is a HAND-VERIFIED map
 * against `api/src/server.ts`; it is deliberately coarse (module level) because
 * function-to-endpoint pairing has to be reviewed by a human, not guessed.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const root = process.cwd();
const check = process.argv.includes("--check");
const outFile = join(root, "docs", "neon-migration-trace.md"); // historical filename retained for links

/**
 * Convex modules that have at least one matching route in `api/src/server.ts`.
 * Verified by hand against the route list on 2026-10-19. "Has routes" does NOT
 * mean parity: it means a screen backed by this module may have an endpoint to
 * move to, and still needs its own ownership/authorization/parity test.
 */
const MODULES_WITH_API_ROUTES = new Map([
  ["auth", "POST /api/auth/register|login|logout, GET /api/me, GET /api/auth/csrf"],
  ["users", "GET|PATCH /api/profile, GET /api/me"],
  ["platform", "GET /api/public-config, GET|POST /api/admin/settings"],
  ["wallet", "GET /api/wallet/summary, GET /api/wallet/ledger, POST /api/admin/users/:id/wallet-adjust"],
  ["shipments", "GET|POST /api/shipments, GET|PATCH /api/shipments/:id, GET /api/admin/shipments"],
  ["tracking", "GET /api/tracking/:trackingNumber"],
  ["marketplace", "GET|POST /api/orders, GET|POST|PATCH|DELETE /api/admin/catalog"],
  ["catalog", "GET /api/catalog"],
  ["notifications", "GET /api/notifications, POST /api/notifications/:id/read, POST /api/notifications/read-all"],
  ["documents", "GET /api/documents"],
  ["tenants", "GET|POST /api/tenants"],
  ["admin", "GET /api/admin/users, GET /api/admin/audit-logs, GET /api/admin/reports"],
  ["adminApi", "GET /api/admin/users, GET /api/admin/transactions, GET /api/admin/audit-logs, GET /api/admin/reports"],
]);

async function walk(dir, out = []) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    if (entry.name === "node_modules" || entry.name === "_generated" || entry.name === "convex") continue;
    const abs = join(dir, entry.name);
    if (entry.isDirectory()) await walk(abs, out);
    else if (/\.tsx?$/.test(entry.name)) out.push(abs);
  }
  return out;
}

/** Convex function references, e.g. `api.wallet.getLedger` or `api.adminApi.adminDashboard`. */
const REF = /(?<![\w.$])api\.([A-Za-z_$][\w$]*)\.([A-Za-z_$][\w$]*)/g;

const consumers = [];
for (const abs of await walk(join(root, "src"))) {
  const rel = relative(root, abs).split(sep).join("/");
  if (rel.startsWith("src/convex/")) continue; // server-side functions are not frontend consumers
  const src = await readFile(abs, "utf8");
  if (!src.includes("_generated/api")) continue; // `api` only resolves in files that import it
  const seen = new Set();
  let m;
  REF.lastIndex = 0;
  while ((m = REF.exec(src))) {
    const fn = `${m[1]}:${m[2]}`;
    if (seen.has(fn)) continue;
    seen.add(fn);
    consumers.push({ file: rel, module: m[1], fn });
  }
}

const byModule = new Map();
for (const { file, module, fn } of consumers) {
  if (!byModule.has(module)) byModule.set(module, new Map());
  const fns = byModule.get(module);
  if (!fns.has(fn)) fns.set(fn, new Set());
  fns.get(fn).add(file);
}

const serverSrc = await readFile(join(root, "api", "src", "server.ts"), "utf8");
const routes = [];
const ROUTE = /\.(get|post|patch|put|delete)\("([^"]+)"/g;
let r;
while ((r = ROUTE.exec(serverSrc))) routes.push(`${r[1].toUpperCase()} ${r[2]}`);

const modules = [...byModule.keys()].sort();
const covered = modules.filter((m) => MODULES_WITH_API_ROUTES.has(m));
const uncovered = modules.filter((m) => !MODULES_WITH_API_ROUTES.has(m));
const fnCount = consumers.length;
const uncoveredFnCount = consumers.filter((c) => !MODULES_WITH_API_ROUTES.has(c.module)).length;

const lines = [];
lines.push("# Legacy Convex function-reference inventory → Turso API");
lines.push("");
lines.push("**Generated by `node scripts/trace-convex-usage.mjs` — do not hand-edit.**");
lines.push("Refresh it after changing frontend Convex calls or `api/src/server.ts`, and");
lines.push("run the `--check` mode when intentionally refreshing the inventory.");
lines.push("");
lines.push("Scope and meaning:");
lines.push("");
lines.push("- *Referenced* = a legacy function reference in frontend source. Vite routes these references through the local compatibility shim; some map to HTTP endpoints and some still use fallback behavior.");
lines.push("- *Module has API routes* = `api/src/server.ts` serves at least one route for that domain (hand-verified map below). It does **not** imply parity, authorization correctness, or that the screen is migrated.");
lines.push("- API-route coverage is not feature parity. Banking transfers, deposits, withdrawals, VTU purchases, and other legacy-only behaviors remain gated until implemented and tested on Turso.");
lines.push("");
lines.push("## Headline");
lines.push("");
lines.push(`| Metric | Value |`);
lines.push(`| --- | --- |`);
lines.push(`| Frontend files importing Convex | ${new Set(consumers.map((c) => c.file)).size} |`);
lines.push(`| Distinct Convex functions referenced | ${fnCount} |`);
lines.push(`| Convex modules referenced | ${modules.length} |`);
lines.push(`| …of which have ≥1 API route | ${covered.length} |`);
lines.push(`| …with **no** API route at all | ${uncovered.length} |`);
lines.push(`| Referenced functions in modules with no API route | ${uncoveredFnCount} |`);
lines.push(`| API routes in \`api/src/server.ts\` | ${routes.length} |`);
lines.push("");
lines.push("## Modules with no matching API route (migration not started for this domain)");
lines.push("");
for (const m of uncovered) {
  const fns = [...byModule.get(m).keys()].sort();
  lines.push(`- \`${m}\` — ${fns.length} function(s): ${fns.map((f) => `\`${f}\``).join(", ")}`);
}
lines.push("");
lines.push("## Modules with at least one API route (per-function parity still to be verified)");
lines.push("");
lines.push("| Convex module | Functions referenced | Verified API routes |");
lines.push("| --- | --- | --- |");
for (const m of covered) {
  const fns = [...byModule.get(m).keys()].sort();
  lines.push(`| \`${m}\` | ${fns.length} | ${MODULES_WITH_API_ROUTES.get(m)} |`);
}
lines.push("");
lines.push("## Full call-site inventory (module:function → referencing files)");
lines.push("");
for (const m of modules) {
  lines.push(`### \`${m}\`${MODULES_WITH_API_ROUTES.has(m) ? " — has API routes" : " — NO API ROUTE"}`);
  lines.push("");
  const fns = [...byModule.get(m).entries()].sort(([a], [b]) => a.localeCompare(b));
  for (const [fn, files] of fns) {
    lines.push(`- \`${fn}\` ← ${[...files].sort().map((f) => `\`${f}\``).join(", ")}`);
  }
  lines.push("");
}
lines.push("## API route inventory (`api/src/server.ts`)");
lines.push("");
for (const route of routes.sort()) lines.push(`- \`${route}\``);
lines.push("");

const content = lines.join("\n");
const previous = await readFile(outFile, "utf8").catch(() => null);

if (check) {
  if (previous !== content) {
    console.error("STALE: docs/neon-migration-trace.md does not match the source. Run: node scripts/trace-convex-usage.mjs");
    process.exitCode = 1;
  } else {
    console.log(`Trace is current: ${fnCount} Convex functions across ${modules.length} modules; ${routes.length} API routes.`);
  }
} else {
  await writeFile(outFile, content);
  console.log(`Wrote docs/neon-migration-trace.md`);
  console.log(`  Convex functions referenced: ${fnCount} (${uncoveredFnCount} in modules with no API route)`);
  console.log(`  Modules: ${modules.length} total, ${covered.length} with routes, ${uncovered.length} without`);
  console.log(`  API routes: ${routes.length}`);
}
